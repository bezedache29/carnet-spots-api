<?php

namespace App\Http\Requests;

use App\Models\Tag;
use Illuminate\Contracts\Validation\ValidationRule;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Support\Str;
use Illuminate\Validation\Rule;

class StoreTagRequest extends FormRequest
{
    /**
     * Determine if the user is authorized to make this request.
     *
     * Ownership is enforced by TagPolicy (via authorizeResource in the
     * controller), not here — this only validates the payload shape.
     */
    public function authorize(): bool
    {
        return true;
    }

    /**
     * The tag created by an earlier attempt of this same creation (same `uuid`, same owner), deleted ones included.
     *
     * Looked up before validation so a replay is recognised even if the rest of its payload no longer
     * validates (e.g. one of its tags was deleted since the first attempt).
     */
    public function replayedTag(): ?Tag
    {
        return once(fn (): ?Tag => is_string($this->input('uuid')) && Str::isUuid($this->input('uuid'))
            ? $this->user()->tags()->withTrashed()->where('uuid', $this->input('uuid'))->first()
            : null);
    }

    /**
     * Get the validation rules that apply to the request.
     *
     * @return array<string, ValidationRule|array<mixed>|string>
     */
    public function rules(): array
    {
        if ($this->replayedTag() !== null) {
            // The controller answers with the existing tag: the rest of the payload is not used.
            return [];
        }

        return [
            // Generated by the client so a replayed offline creation is recognised instead of duplicated.
            // At this point it is not one of the user's own uuids (see replayedTag()), so any match is another user's.
            'uuid' => [
                'sometimes',
                'uuid',
                Rule::unique('tags', 'uuid'),
            ],
            'name' => [
                'required',
                'string',
                'max:50',
                Rule::unique('tags', 'name')
                    ->where('owner_id', $this->user()->id)
                    ->withoutTrashed(),
            ],
        ];
    }
}
