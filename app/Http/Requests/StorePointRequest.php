<?php

namespace App\Http\Requests;

use App\Enums\PointStatus;
use App\Enums\PointVisibility;
use App\Models\Point;
use Illuminate\Contracts\Validation\ValidationRule;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Support\Str;
use Illuminate\Validation\Rule;

class StorePointRequest extends FormRequest
{
    /**
     * Determine if the user is authorized to make this request.
     *
     * Ownership is enforced by PointPolicy (via HasMiddleware in the
     * controller), not here — this only validates the payload shape.
     */
    public function authorize(): bool
    {
        return true;
    }

    /**
     * The point created by an earlier attempt of this same creation (same `uuid`, same owner), deleted ones included.
     *
     * Looked up before validation so a replay is recognised even if the rest of its payload no longer
     * validates (e.g. one of its tags was deleted since the first attempt).
     */
    public function replayedPoint(): ?Point
    {
        return once(fn (): ?Point => is_string($this->input('uuid')) && Str::isUuid($this->input('uuid'))
            ? $this->user()->points()->withTrashed()->where('uuid', $this->input('uuid'))->first()
            : null);
    }

    /**
     * Get the validation rules that apply to the request.
     *
     * @return array<string, ValidationRule|array<mixed>|string>
     */
    public function rules(): array
    {
        if ($this->replayedPoint() !== null) {
            // The controller answers with the existing point: the rest of the payload is not used.
            return [];
        }

        return [
            // Generated by the client so a replayed offline creation is recognised instead of duplicated.
            // At this point it is not one of the user's own uuids (see replayedPoint()), so any match is another user's.
            'uuid' => [
                'sometimes',
                'uuid',
                Rule::unique('points', 'uuid'),
            ],
            'title' => ['nullable', 'string', 'max:255'],
            'latitude' => ['required', 'numeric', 'between:-90,90'],
            'longitude' => ['required', 'numeric', 'between:-180,180'],
            'note' => ['nullable', 'string', 'max:10000'],
            'status' => ['sometimes', Rule::enum(PointStatus::class)],
            'visited_at' => ['nullable', 'date'],
            'visibility' => ['sometimes', Rule::enum(PointVisibility::class)],
            'tag_ids' => ['sometimes', 'array'],
            'tag_ids.*' => [
                'integer',
                Rule::exists('tags', 'id')->where('owner_id', $this->user()->id)->whereNull('deleted_at'),
            ],
        ];
    }
}
