<?php

namespace App\Http\Controllers;

use App\Http\Requests\NearbyPointsRequest;
use App\Http\Requests\StorePointRequest;
use App\Http\Requests\UpdatePointRequest;
use App\Http\Resources\PointResource;
use App\Models\Point;
use Dedoc\Scramble\Attributes\Endpoint;
use Illuminate\Database\UniqueConstraintViolationException;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Resources\Json\AnonymousResourceCollection;
use Illuminate\Http\Response;
use Illuminate\Routing\Controllers\HasMiddleware;
use Illuminate\Routing\Controllers\Middleware;
use Illuminate\Support\Facades\DB;

class PointController extends Controller implements HasMiddleware
{
    public const PER_PAGE = 50;

    /**
     * @return array<int, Middleware>
     */
    public static function middleware(): array
    {
        return [
            new Middleware('can:viewAny,'.Point::class, only: ['index', 'nearby']),
            new Middleware('can:create,'.Point::class, only: ['store']),
            new Middleware('can:view,point', only: ['show']),
            new Middleware('can:update,point', only: ['update']),
            new Middleware('can:delete,point', only: ['destroy']),
        ];
    }

    #[Endpoint(title: 'List points', description: 'Returns the points owned by the authenticated user, most recent first (ties broken by id, so pages never overlap), 50 per page, with tags eager-loaded.')]
    public function index(): AnonymousResourceCollection
    {
        return PointResource::collection(
            request()->user()->points()->with('tags')->latest()->latest('id')->paginate(self::PER_PAGE)
        );
    }

    #[Endpoint(title: 'Find nearby points', description: 'Returns the authenticated user\'s points within `radius` km (default 20, max 20000 — effectively unbounded, e.g. large enough for a nationwide search) of `lat`/`lng`, closest first, capped at `limit` results (default 50, max 100). Each point includes a `distance_km` field.')]
    public function nearby(NearbyPointsRequest $request): AnonymousResourceCollection
    {
        $lat = (float) $request->validated('lat');
        $lng = (float) $request->validated('lng');
        $radius = (float) $request->validated('radius', 20);
        $limit = (int) $request->validated('limit', 50);

        $points = $request->user()->points()
            ->nearby($lat, $lng, $radius)
            ->limit($limit)
            ->with('tags')
            ->get();

        return PointResource::collection($points);
    }

    #[Endpoint(title: 'Create a point', description: 'Creates a point for the authenticated user. `tag_ids` is optional and must reference tags owned by the same user. `uuid` is optional and generated by the client: sending a uuid that already exists returns that point (200) instead of creating a duplicate, so an offline creation can be replayed safely — or 404 if it has been deleted since.')]
    public function store(StorePointRequest $request): JsonResponse
    {
        if ($request->replayedPoint() !== null) {
            return $this->replayedCreation($request->replayedPoint());
        }

        try {
            $point = DB::transaction(function () use ($request): Point {
                $point = $request->user()->points()->create($request->safe()->except('tag_ids'));

                if ($request->has('tag_ids')) {
                    $point->tags()->sync($request->validated('tag_ids'));
                }

                return $point;
            });
        } catch (UniqueConstraintViolationException $exception) {
            // The same creation sent twice at once: the other request inserted this uuid first.
            $point = $request->user()->points()->withTrashed()->where('uuid', $request->validated('uuid'))->first();

            return $point === null ? throw $exception : $this->replayedCreation($point);
        }

        return (new PointResource($point->load('tags')))->response()->setStatusCode(201);
    }

    #[Endpoint(title: 'Get a point', description: 'Returns a single point owned by the authenticated user.')]
    public function show(Point $point): PointResource
    {
        return new PointResource($point->load('tags'));
    }

    #[Endpoint(title: 'Update a point', description: "Updates a point owned by the authenticated user. Every field is optional (PATCH-style), e.g. send only `status`/`visited_at`/`note` to mark a point as visited. `tag_ids`, when present, replaces the point's tags and must reference tags owned by the same user. `base_updated_at` is optional: the `updated_at` of the version the client edited; if the point changed since, nothing is saved and 409 is returned with the current point. All-or-nothing: if saving fails, an error is returned and neither the fields nor the tags change.")]
    public function update(UpdatePointRequest $request, Point $point): PointResource|JsonResponse
    {
        if ($this->changedSince($point, $request->validated('base_updated_at'))) {
            return (new PointResource($point->load('tags')))
                ->additional(['message' => 'The point was changed since base_updated_at.'])
                ->response()
                ->setStatusCode(409);
        }

        DB::transaction(function () use ($request, $point): void {
            $point->update($request->safe()->except(['tag_ids', 'base_updated_at']));

            if ($request->has('tag_ids')) {
                $changes = $point->tags()->sync($request->validated('tag_ids'));

                // Changing only the tags doesn't save the point itself: bump updated_at so the sync sees it.
                if (array_merge(...array_values($changes)) !== []) {
                    $point->touch();
                }
            }
        });

        return new PointResource($point->load('tags'));
    }

    #[Endpoint(title: 'Delete a point', description: 'Soft-deletes a point owned by the authenticated user, so the sync can tell other devices it is gone. Deleting an already deleted point answers 204 too, so the call can be replayed.')]
    public function destroy(Point $point): Response
    {
        if (! $point->trashed()) {
            $point->delete();
        }

        return response()->noContent();
    }

    /**
     * Answer a replayed creation with the point the first attempt created: 200, or 404 if it was deleted since.
     */
    private function replayedCreation(Point $point): JsonResponse
    {
        abort_if($point->trashed(), 404);

        return (new PointResource($point->load('tags')))->response();
    }
}
